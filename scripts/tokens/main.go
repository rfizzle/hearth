// Command tokens writes the web and chart mirrors of the design tokens.
//
// Usage: tokens <tokens.json> <theme.css> <palette.go>
//
// It reads the same tokens.json the app and tokens-check read and writes
// scripts/tailwind/theme.css (a Tailwind @theme block with a CSS variable for
// every colour, the dark values under prefers-color-scheme, and the spacing
// and radius scales) and internal/render/chart/palette.go (the six chart hues
// as light and dark hex constants). Output is a pure function of the JSON:
// keys are sorted and nothing carries a time.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// chartHues is how many chart.N tokens the palette holds.
const chartHues = 6

// The spacing and radius scales mirror Theme.Spacing and Theme.Radius in
// HearthDesign; they are not in the JSON because nothing contrast-checks them.
var (
	spacing = []struct {
		name string
		px   int
	}{{"xs", 4}, {"sm", 8}, {"md", 12}, {"lg", 16}, {"xl", 24}, {"xxl", 32}}
	radii = []struct {
		name string
		px   int
	}{{"sm", 6}, {"md", 10}, {"lg", 16}}
)

var hexColour = regexp.MustCompile(`^#[0-9A-Fa-f]{6}$`)

type colorPair struct {
	Light string `json:"light"`
	Dark  string `json:"dark"`
}

type tokens struct {
	Colors map[string]colorPair `json:"colors"`
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: tokens <tokens.json> <theme.css> <palette.go>")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	css, palette, err := generate(data)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	for path, content := range map[string][]byte{os.Args[2]: css, os.Args[3]: palette} {
		if err := os.WriteFile(path, content, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

// generate returns theme.css and palette.go for the tokens in data.
func generate(data []byte) (css, palette []byte, err error) {
	var t tokens
	if err := json.Unmarshal(data, &t); err != nil {
		return nil, nil, fmt.Errorf("tokens: %w", err)
	}
	names := make([]string, 0, len(t.Colors))
	for name, c := range t.Colors {
		if !hexColour.MatchString(c.Light) || !hexColour.MatchString(c.Dark) {
			return nil, nil, fmt.Errorf("tokens: colour %q is not a #RRGGBB pair", name)
		}
		names = append(names, name)
	}
	sort.Strings(names)
	for i := 1; i <= chartHues; i++ {
		if _, ok := t.Colors["chart."+strconv.Itoa(i)]; !ok {
			return nil, nil, fmt.Errorf("tokens: no colour chart.%d", i)
		}
	}

	var b bytes.Buffer
	b.WriteString("/* Code generated by scripts/tokens from tokens.json; DO NOT EDIT. */\n")
	b.WriteString("@theme {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "  --color-%s: %s;\n", cssName(n), strings.ToUpper(t.Colors[n].Light))
	}
	for _, s := range spacing {
		fmt.Fprintf(&b, "  --spacing-%s: %dpx;\n", s.name, s.px)
	}
	for _, r := range radii {
		fmt.Fprintf(&b, "  --radius-%s: %dpx;\n", r.name, r.px)
	}
	b.WriteString("}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "    --color-%s: %s;\n", cssName(n), strings.ToUpper(t.Colors[n].Dark))
	}
	b.WriteString("  }\n}\n")
	css = b.Bytes()

	var p bytes.Buffer
	p.WriteString("// Code generated by scripts/tokens from tokens.json; DO NOT EDIT.\n\n")
	p.WriteString("package chart\n\n// The chart hues, light and dark, by series order. Each holds 3:1 against\n// surface.card in its appearance (make tokens-check).\nconst (\n")
	for i := 1; i <= chartHues; i++ {
		c := t.Colors["chart."+strconv.Itoa(i)]
		fmt.Fprintf(&p, "\tChart%dLight = %q\n\tChart%dDark = %q\n", i, strings.ToUpper(c.Light), i, strings.ToUpper(c.Dark))
	}
	p.WriteString(")\n\n// PaletteLight and PaletteDark are the hues in series order.\nvar (\n\tPaletteLight = [6]string{")
	for i := 1; i <= chartHues; i++ {
		fmt.Fprintf(&p, "Chart%dLight, ", i)
	}
	p.WriteString("}\n\tPaletteDark = [6]string{")
	for i := 1; i <= chartHues; i++ {
		fmt.Fprintf(&p, "Chart%dDark, ", i)
	}
	p.WriteString("}\n)\n")
	palette, err = format.Source(p.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("tokens: format palette: %w", err)
	}
	return css, palette, nil
}

// cssName turns a token name such as "tone.positive.fill" into a CSS
// identifier tail, "tone-positive-fill".
func cssName(n string) string { return strings.ReplaceAll(n, ".", "-") }
