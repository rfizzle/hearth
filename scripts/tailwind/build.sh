#!/usr/bin/env bash
# Build internal/render/html/deliverable.css with the pinned Tailwind
# standalone CLI.
#
# Usage: build.sh [output]   (default: internal/render/html/deliverable.css)
#
# The CLI for this host is downloaded once into .cache/tailwind/<version>/
# (never into the tree), its sha256 is checked against SHA256SUMS before it is
# marked executable or run, and a mismatch refuses. The build itself reads only
# local files, so it needs no network once the binary is cached.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
version="$(tr -d '[:space:]' < "$here/VERSION")"
out="${1:-$root/internal/render/html/deliverable.css}"
cache="${HEARTH_CACHE_DIR:-$root/.cache}/tailwind/$version"
templates="$root/internal/render/html/templates"

sha256_stdin() {
	if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -d' ' -f1; else shasum -a 256 | cut -d' ' -f1; fi
}

case "$(uname -s)-$(uname -m)" in
	Darwin-arm64) asset=tailwindcss-macos-arm64 ;;
	Linux-aarch64 | Linux-arm64) asset=tailwindcss-linux-arm64 ;;
	Linux-x86_64) asset=tailwindcss-linux-x64 ;;
	*) echo "tailwind: no pinned CLI for $(uname -s) $(uname -m)" >&2; exit 1 ;;
esac

want="$(awk -v a="$asset" '$1 !~ /^#/ && $2 == a {print $1}' "$here/SHA256SUMS")"
[ -n "$want" ] || { echo "tailwind: SHA256SUMS has no entry for $asset" >&2; exit 1; }

bin="$cache/$asset"
mkdir -p "$cache"
if [ ! -f "$bin" ]; then
	curl -fsSL "https://github.com/tailwindlabs/tailwindcss/releases/download/$version/$asset" -o "$bin.part"
	mv "$bin.part" "$bin"
fi
got="$(sha256_stdin < "$bin")"
if [ "$got" != "$want" ]; then
	rm -f "$bin"
	echo "tailwind: $asset sha256 is $got, SHA256SUMS says $want; refusing to run it" >&2
	exit 1
fi
chmod +x "$bin"

# The input hash covers everything the CSS is built from: the two CSS inputs
# and every template, in a fixed order.
hash="$( {
	cat "$here/input.css" "$here/theme.css"
	(cd "$templates" && find . -type f | LC_ALL=C sort | while read -r f; do printf '%s\n' "$f"; cat "$f"; done)
} | sha256_stdin)"

tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT
(cd "$here" && "$bin" -i input.css -o "$tmp" --minify)
{
	printf '/* deliverable.css: tailwindcss %s, input sha256 %s. Generated by scripts/tailwind/build.sh; DO NOT EDIT. */\n' "$version" "$hash"
	cat "$tmp"
} > "$out"
echo "tailwind: wrote ${out#"$root"/} (input $hash)"
